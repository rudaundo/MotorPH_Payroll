    private void jb_submitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jb_submitActionPerformed
     
        try {

            // Get the employee ID.
            String employeeID = text_id.getText().trim();

            // Get the selected date.
            Date selectedDate = jd_start.getDate();

            if (selectedDate == null) {
                JOptionPane.showMessageDialog(
                        this,
                        "Please select the overtime date."
                );
                return;
            }

            LocalDate overtimeDate = selectedDate.toInstant()
                    .atZone(ZoneId.systemDefault())
                    .toLocalDate();

            // Get the selected start and end times.
            Date startDate = (Date) js_startTime.getValue();

            Date endDate = (Date) js_endTime.getValue();

            LocalTime startTime = startDate.toInstant()
                    .atZone(ZoneId.systemDefault())
                    .toLocalTime();

            LocalTime endTime = endDate.toInstant()
                    .atZone(ZoneId.systemDefault())
                    .toLocalTime();

            // Get the reason.
            String reason = jt_reason.getText().trim();          

            // Save through OvertimeService.
            String overtimeID = overtimeService.submitRequest(
                    employeeID,
                    overtimeDate,
                    startTime,
                    endTime,
                    reason
            );

            // Calculate the displayed duration.
            double totalHours =
                    java.time.Duration.between(
                            startTime,
                            endTime
                    ).toMinutes() / 60.0;

            JOptionPane.showMessageDialog(
                    this,
                    "Overtime request submitted successfully!\n\n"
                    + "Request ID: " + overtimeID + "\n"
                    + "Date: " + overtimeDate + "\n"
                    + "Start Time: " + startTime + "\n"
                    + "End Time: " + endTime + "\n"
                    + "Total Hours: "
                    + String.format("%.2f", totalHours) + "\n"
                    + "Status: PENDING",
                    "Overtime Request",
                    JOptionPane.INFORMATION_MESSAGE
            );

            // Clear the form after successful submission.
            jd_start.setDate(null);
            jt_reason.setText("");

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Invalid Request",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (IOException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to save overtime request:\n"
                    + e.getMessage(),
                    "File Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
        
    }//GEN-LAST:event_jb_submitActionPerformed

