    private void jb_loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jb_loginActionPerformed
        
         // Get the username
         
    String username = text_user.getText().trim();

    // Get the password safely from JPasswordField
    char[] passwordChars = text_password.getPassword();
    String password = new String(passwordChars);

    // Get the selected role
    String role = String.valueOf(
            jc_level.getSelectedItem()
    );

    try {

        // Validate empty fields
        if (username.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Username Field is empty"
            );

            return;
        }

        if (password.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Password Field is empty"
            );

            return;
        }

        if (jc_level.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a role"
            );

            return;
        }

        // Authenticate using AuthenticationService
        UserData user = authenticationService.authenticate(
                username,
                password,
                role
        );

        // Clear the temporary password character array
        java.util.Arrays.fill(passwordChars, '\0');

        // Check authentication result
        if (user != null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Login Successful!"
            );

            // Retrieve the employee number
            String empID = user.getempNo();
            

            // Open the appropriate dashboard
            if ("HumanResources".equalsIgnoreCase(user.getrole())) {

                GUIHRDashboard nextForm = new GUIHRDashboard(empID);

                nextForm.setVisible(true);

            } else if ("Regular".equalsIgnoreCase(user.getrole())) {

                GUIEmpDashboard nextForm = new GUIEmpDashboard(empID);

                nextForm.setVisible(true);

            } else if ("Accounting".equalsIgnoreCase(user.getrole())) {

                GUIAcctgDashboard nextForm = new GUIAcctgDashboard(empID);

                nextForm.setVisible(true);
                
            } else if ("Chief".equalsIgnoreCase(user.getrole())) {

                GUIAcctgDashboard nextForm = new GUIAcctgDashboard(empID);

                nextForm.setVisible(true);

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "No dashboard is configured for this role."
                );

                return;
            }

            // Close the login form after successful navigation
            this.dispose();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid Username, Password, or Role!"
            );
        }

    } catch (IOException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error reading user data: " + e.getMessage()
        );

        e.printStackTrace();

    } catch (CsvException ex) {
            Logger.getLogger(GUILogin.class.getName()).log(Level.SEVERE, null, ex);
        } finally {

        // Clear the password field
        text_password.setText("");
    }
              
    }//GEN-LAST:event_jb_loginActionPerformed

