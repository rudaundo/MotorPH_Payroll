    private void jb_submitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jb_submitActionPerformed
 
         try {
            String employeeID = text_id.getText().trim();

            // Check that both dates have been selected.
            Date selectedStart = jd_start.getDate();
            Date selectedEnd = jd_end.getDate();

            if (selectedStart == null || selectedEnd == null) {
                JOptionPane.showMessageDialog(
                        this,
                        "Please select both the start date and end date.",
                        "Missing Dates",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
        }

            // Convert the selected dates into LocalDate.
            LocalDate startDate = selectedStart.toInstant()
                                   .atZone(ZoneId.systemDefault())
                                   .toLocalDate();

            LocalDate endDate = selectedEnd.toInstant()
                                .atZone(ZoneId.systemDefault())
                                .toLocalDate();

            // Get the selected leave type.
            String leaveType = jc_leaveType.getSelectedItem().toString();

            // Get the reason.
            String reason = jt_reason.getText().trim();

            if (reason.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "Please provide a reason for your leave.",
                        "Missing Reason",
                        JOptionPane.WARNING_MESSAGE
                );
                jt_reason.requestFocus();
                return;
            }

            // Calculate the requested calendar days, including both dates.
            long totalDays = java.time.temporal.ChronoUnit.DAYS.between(startDate, endDate) + 1;

            // Submit through the service class.
            String leaveID = leaveService.submitRequest(
                    employeeID,
                    leaveType,
                    startDate,
                    endDate,
                    reason
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Leave request submitted successfully!\n\n"
                    + "Leave ID: " + leaveID + "\n"
                    + "Employee ID: " + employeeID + "\n"
                    + "Leave Type: " + leaveType + "\n"
                    + "Start Date: " + startDate + "\n"
                    + "End Date: " + endDate + "\n"
                    + "Total Calendar Days: " + totalDays + "\n"
                    + "Status: PENDING",
                    "Leave Request Submitted",
                    JOptionPane.INFORMATION_MESSAGE
            );

            clearLeaveForm();

        } catch (IllegalArgumentException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "Invalid Leave Request",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (IOException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to save the leave request:\n" + ex.getMessage(),
                    "File Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }       
        
    }//GEN-LAST:event_jb_submitActionPerformed

