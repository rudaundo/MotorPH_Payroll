    private void jb_loadEmployeeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jb_loadEmployeeActionPerformed
       
         String employeeID = jt_employeeID.getText().trim();

            try {

                loadedEmployee = registrationService.findEmployee(employeeID);

                if (loadedEmployee == null) {

                    jt_employeeName.setText("");
                    jt_position.setText("");

                    JOptionPane.showMessageDialog(
                            this,
                            "Employee ID was not found.",
                            "Employee Not Found",
                            JOptionPane.ERROR_MESSAGE
                    );

                    return;
                }

                jt_employeeName.setText(loadedEmployee.getFullName());
                jt_position.setText(loadedEmployee.getPosition());

                JOptionPane.showMessageDialog(
                        this,
                        "Employee information loaded successfully.",
                        "Employee Found",
                        JOptionPane.INFORMATION_MESSAGE
                );

            } catch (IllegalArgumentException e) {

                JOptionPane.showMessageDialog(
                        this,
                        e.getMessage(),
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
            } catch (IOException ex) {
            Logger.getLogger(GUIRegistration.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }//GEN-LAST:event_jb_loadEmployeeActionPerformed

