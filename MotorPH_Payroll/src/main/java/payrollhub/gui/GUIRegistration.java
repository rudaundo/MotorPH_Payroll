    private void jb_confirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jb_confirmActionPerformed
       
        String employeeID = jt_employeeID.getText().trim();
        String userName = jt_userName.getText().trim();

        String password = new String(jt_createPassword.getPassword());
        String confirmPassword = new String(jt_confirmPassword.getPassword());

        // Check whether employee details were loaded
        if (loadedEmployee == null
                || !loadedEmployee.getEmpNo().equalsIgnoreCase(employeeID)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please load the employee details first.",
                    "Employee Verification Required",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        // Validate required fields
        if (userName.isEmpty() || password.isEmpty()
                || confirmPassword.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please complete all registration fields.",
                    "Missing Information",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        // Check password length
        if (password.length() < 8) {

            JOptionPane.showMessageDialog(
                    this,
                    "Password must contain at least 8 characters.",
                    "Invalid Password",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        // Check password confirmation
        if (!password.equals(confirmPassword)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Passwords do not match.",
                    "Password Mismatch",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        // Ask for final confirmation before saving
        int choice = JOptionPane.showConfirmDialog(
                this,
                "Please review your registration details:\n\n"
                + "Employee ID: " + loadedEmployee.getEmpNo() + "\n"
                + "Employee Name: " + loadedEmployee.getFullName() + "\n"
                + "Position: " + loadedEmployee.getPosition() + "\n"
                + "Username: " + userName + "\n\n"
                + "Do you want to register this account?",
                "Confirm Registration",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (choice != JOptionPane.YES_OPTION) {
            return;
        }

        try {

            // Save account to users.csv
            registrationService.registerUser(
                    employeeID,
                    userName,
                    password
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Your account has been successfully registered!",
                    "Registration Successful",
                    JOptionPane.INFORMATION_MESSAGE
            );

            // Clear the form after successful registration
            jt_employeeID.setText("");
            jt_employeeName.setText("");
            jt_position.setText("");
            jt_userName.setText("");
            jt_createPassword.setText("");
            jt_confirmPassword.setText("");

            loadedEmployee = null;

        } catch (IOException | IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Registration Failed",
                    JOptionPane.ERROR_MESSAGE
            );
        }
        
    }//GEN-LAST:event_jb_confirmActionPerformed

